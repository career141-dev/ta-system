import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { validateWorkLocations, activeWorkLocationIds, inWorkLocation, requireWorkLocation, workLocationView, locationEodComplete } from "../src/lib/workLocations";
import { eodDraftKeys } from "../src/lib/eodDraft";

const locations = [{ id: "m", name: "Mumbai", vacancies: 2 }, { id: "d", name: "Delhi", vacancies: 1 }];
assert.equal(validateWorkLocations(locations).reduce((n, l) => n + l.vacancies, 0), 3);
assert.throws(() => validateWorkLocations([{ ...locations[0], vacancies: 1.5 }]), /whole number/);
assert.throws(() => validateWorkLocations([{ ...locations[0], vacancies: 0 }]), /whole number/);
assert.throws(() => validateWorkLocations([locations[0], { ...locations[1], name: " mUMbai " }]), /one row/);
assert.throws(() => validateWorkLocations([locations[0]], locations), /Archive/);
assert.deepEqual(validateWorkLocations([locations[1], { ...locations[0], name: "Greater Mumbai" }], locations).map(l => l.id), ["d", "m"]);
assert.deepEqual(activeWorkLocationIds({ workLocations: [locations[0], { ...locations[1], archived: true }] }), ["m"]);
assert.equal(inWorkLocation({}, "m"), false);
assert.equal(inWorkLocation({}, ""), true);
assert.throws(() => requireWorkLocation({ workLocations: locations }), /Select/);
assert.equal(requireWorkLocation({ workLocations: [locations[0]] })?.id, "m");
assert.equal(workLocationView({ workLocations: locations }), "");
assert.throws(() => workLocationView({ workLocations: locations }, "forged"), /not on this job/);
assert.equal(locationEodComplete(["m", "d"], [{ workLocationId: "m" }, {}]), false);
assert.equal(locationEodComplete(["m", "d"], [{ workLocationId: "m" }, { workLocationId: "d" }]), true);
const keys = (actor: string, loc: string, date = "2026-10-21") => eodDraftKeys("job", "director", "21 Oct", actor, loc, undefined, date);
assert.notDeepEqual(keys("a", "m"), keys("a", "d"));
assert.notDeepEqual(keys("a", "m"), keys("b", "m"));
assert.notDeepEqual(keys("a", "m"), keys("a", "m", "2026-10-22"));

process.chdir(fs.mkdtempSync(path.join(os.tmpdir(), "c141-locations-")));
const { repo } = await import("@/data/store");
const { getScopedLinkVaultEntries, buildOpeningExcelAttachment } = await import("@/lib/linkExport");
const { shortlistRows, effortRow } = await import("@/lib/eod");
const opening = repo.openings()[0];
const ta = repo.users().find(u => u.role === "ta")!;
repo.updateOpening(opening.id, { workLocations: locations, headcount: 3, locations: ["Mumbai", "Delhi"] });
const m1 = repo.addLinkLevel(opening.id, ta.id, "m");
assert.equal(m1, 1);
assert.equal(repo.addLinkLevel(opening.id, ta.id, "d"), 1);
const mRow = repo.addLink(opening.id, "https://www.linkedin.com/in/mumbai-test", ta.id, "Mumbai Candidate", "shortlisted", "m", 1);
const dRow = repo.addLink(opening.id, "https://www.linkedin.com/in/delhi-test", ta.id, "Delhi Candidate", "shortlisted", "d", 1);
const pending = repo.addLink(opening.id, "https://www.linkedin.com/in/unassigned-test", ta.id, "Unassigned Candidate");
assert.equal(repo.linkEntry(pending)?.workLocationId, undefined, "Multiple cities never guess the first city");
repo.addLinkLevel(opening.id, ta.id, "m");
const mOld = repo.addLink(opening.id, "https://www.linkedin.com/in/mumbai-old-level", ta.id, "Mumbai L1", "shortlisted", "m", 1);
assert.equal(repo.linkEntry(mOld)?.level, 1, "Adding within a selected older L stays in that L");
repo.renameLinkLevel(opening.id, ta.id, 1, "Mumbai search", "m");
assert.equal(repo.linkLevels(opening.id, ta.id, "d")[0].name, undefined);
const mApp = repo.linkToApplication(mRow, ta.id);
const dApp = repo.linkToApplication(dRow, ta.id);
assert.ok(mApp.ok && dApp.ok);
assert.equal(repo.application(mApp.applicationId)?.workLocationId, "m");
assert.equal(repo.application(dApp.applicationId)?.workLocationId, "d");
assert.equal(getScopedLinkVaultEntries(opening.id, ta, "m").entries.length, 2);
assert.equal(getScopedLinkVaultEntries(opening.id, ta, "d").entries.map(r => r.id).join(), dRow);
assert.ok(buildOpeningExcelAttachment(opening.id, ta, "Engineer", "m")!.filename.includes(" - Mumbai - "));
assert.equal(effortRow(opening.id, ta, new Date(), "d").lEffort, 1);
assert.equal(shortlistRows(opening.id, ta.id, "director", undefined, "m").some(r => r.applicationId === dApp.applicationId), false);
repo.deleteLinkLevel(opening.id, ta.id, 1, "m");
assert.equal(repo.linkEntry(mRow)?.level, null);
assert.equal(repo.linkEntry(dRow)?.level, 1, "Deleting Mumbai L1 cannot change Delhi L1");
assert.equal(repo.addLinkLevel(opening.id, ta.id, "m"), 1, "Mumbai L1 is free again once its rows left it (22 Oct)");
console.log("Location validation, identity, L-sheet isolation, application inheritance, drafts and scoped exports passed.");
